//! macOS-only pieces of Clipboard: reading and writing the general
//! pasteboard and the app in front (the source of each copy). Elsewhere
//! these are no-ops,
//! so the tool still builds and its tests run on Linux.
#![cfg_attr(not(target_os = "macos"), allow(dead_code))]

use super::store::Clip;
use std::path::PathBuf;

/// Pasteboard types apps use to say "don't keep this" (nspasteboard.org).
pub const CONCEALED_TYPES: [&str; 1] = ["org.nspasteboard.ConcealedType"];
/// Marks for clips no history should keep at all, whatever the settings
/// (nspasteboard.org): a temporary hand-over, or content no person copied.
pub const TRANSIENT_TYPES: [&str; 2] = ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"];

/// A `file://` URL as a path (percent-decoded).
pub fn file_url_path(url: &str) -> Option<PathBuf> {
    let rest = url.strip_prefix("file://")?;
    let rest = rest.strip_prefix("localhost").unwrap_or(rest);
    let bytes = rest.as_bytes();
    let mut out = Vec::with_capacity(bytes.len());
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'%' && i + 2 < bytes.len() {
            if let Some(b) = std::str::from_utf8(&bytes[i + 1..i + 3]).ok().and_then(|h| u8::from_str_radix(h, 16).ok()) {
                out.push(b);
                i += 3;
                continue;
            }
        }
        out.push(bytes[i]);
        i += 1;
    }
    let s = String::from_utf8(out).ok()?;
    let s = s.trim_end_matches('/');
    (!s.is_empty()).then(|| PathBuf::from(s))
}

/// What to put on the pasteboard.
pub struct Write<'a> {
    pub text: Option<&'a str>,
    pub rtf: Option<&'a [u8]>,
    pub html: Option<&'a [u8]>,
    pub png: Option<&'a [u8]>,
    pub files: &'a [PathBuf],
}

#[cfg(target_os = "macos")]
mod imp {
    use super::{Clip, Write, CONCEALED_TYPES, TRANSIENT_TYPES};
    use objc2::rc::Retained;
    use objc2::runtime::ProtocolObject;
    use objc2::AnyThread;
    use objc2_app_kit::{
        NSBitmapImageFileType, NSBitmapImageRep, NSImage, NSPasteboard, NSPasteboardTypeFileURL, NSPasteboardTypeHTML, NSPasteboardTypePNG, NSPasteboardTypeRTF,
        NSPasteboardTypeString, NSPasteboardTypeTIFF, NSPasteboardWriting, NSWorkspace,
    };
    use objc2_foundation::{NSArray, NSData, NSDictionary, NSString, NSURL};

    pub fn change_count() -> isize {
        NSPasteboard::generalPasteboard().changeCount()
    }

    /// The app in front: (name, bundle id, process id).
    pub fn front_app() -> Option<(String, String, i32)> {
        let app = NSWorkspace::sharedWorkspace().frontmostApplication()?;
        let name = app.localizedName().map(|n| n.to_string()).unwrap_or_default();
        let bundle = app.bundleIdentifier().map(|b| b.to_string()).unwrap_or_default();
        Some((name, bundle, app.processIdentifier()))
    }

    fn data(pb: &NSPasteboard, ty: &NSString) -> Option<Vec<u8>> {
        pb.dataForType(ty).map(|d| d.to_vec())
    }

    /// TIFF (what screenshots and many apps put there) → PNG.
    fn tiff_to_png(tiff: &[u8]) -> Option<Vec<u8>> {
        let d = NSData::with_bytes(tiff);
        let rep = NSBitmapImageRep::imageRepWithData(&d)?;
        let png = unsafe { rep.representationUsingType_properties(NSBitmapImageFileType::PNG, &NSDictionary::new()) }?;
        Some(png.to_vec())
    }

    /// Read what's on the pasteboard now. `max_image` caps image bytes.
    pub fn read(max_image: usize, with_images: bool) -> Clip {
        let pb = NSPasteboard::generalPasteboard();
        let mut c = Clip::default();
        let types: Vec<String> = pb.types().map(|t| t.iter().map(|s| s.to_string()).collect()).unwrap_or_default();
        c.concealed = types.iter().any(|t| CONCEALED_TYPES.contains(&t.as_str()));
        c.transient = types.iter().any(|t| TRANSIENT_TYPES.contains(&t.as_str()));
        if let Some((name, bundle, _)) = front_app() {
            c.app = name;
            c.bundle = bundle;
        }
        if c.concealed || c.transient {
            // never read a password into memory; the caller decides whether
            // concealed items are wanted and reads again if so
            return c;
        }
        read_into(&pb, &mut c, &types, max_image, with_images);
        c
    }

    /// Read a concealed item anyway (the user turned that on).
    pub fn read_concealed(max_image: usize, with_images: bool) -> Clip {
        let pb = NSPasteboard::generalPasteboard();
        let types: Vec<String> = pb.types().map(|t| t.iter().map(|s| s.to_string()).collect()).unwrap_or_default();
        let mut c = Clip { concealed: true, ..Default::default() };
        if let Some((name, bundle, _)) = front_app() {
            c.app = name;
            c.bundle = bundle;
        }
        read_into(&pb, &mut c, &types, max_image, with_images);
        c
    }

    fn read_into(pb: &NSPasteboard, c: &mut Clip, types: &[String], max_image: usize, with_images: bool) {
        let has = |t: &NSString| types.iter().any(|x| x.as_str() == t.to_string());
        unsafe {
            // files: one item per file
            if has(NSPasteboardTypeFileURL) {
                if let Some(items) = pb.pasteboardItems() {
                    for it in items.iter() {
                        if let Some(u) = it.stringForType(NSPasteboardTypeFileURL) {
                            if let Some(p) = super::file_url_path(&u.to_string()) {
                                c.files.push(p);
                            }
                        }
                    }
                }
            }
            if c.files.is_empty() && with_images {
                let png = data(pb, NSPasteboardTypePNG).or_else(|| data(pb, NSPasteboardTypeTIFF).and_then(|t| tiff_to_png(&t)));
                c.png = png.filter(|p| p.len() <= max_image);
            }
            c.text = pb.stringForType(NSPasteboardTypeString).map(|s| s.to_string());
            if c.png.is_none() && c.files.is_empty() {
                c.rtf = data(pb, NSPasteboardTypeRTF);
                c.html = data(pb, NSPasteboardTypeHTML);
            }
        }
    }

    /// Put an entry on the pasteboard. Returns the new change count.
    pub fn write(w: &Write) -> Option<isize> {
        let pb = NSPasteboard::generalPasteboard();
        pb.clearContents();
        let mut ok = false;
        unsafe {
            if !w.files.is_empty() {
                let urls: Vec<Retained<ProtocolObject<dyn NSPasteboardWriting>>> =
                    w.files.iter().map(|p| ProtocolObject::from_retained(NSURL::fileURLWithPath(&NSString::from_str(&p.to_string_lossy())))).collect();
                ok = pb.writeObjects(&NSArray::from_retained_slice(&urls));
            } else if let Some(png) = w.png {
                let d = NSData::with_bytes(png);
                ok = pb.setData_forType(Some(&d), NSPasteboardTypePNG);
                if let Some(img) = NSImage::initWithData(NSImage::alloc(), &d) {
                    if let Some(tiff) = img.TIFFRepresentation() {
                        ok |= pb.setData_forType(Some(&tiff), NSPasteboardTypeTIFF);
                    }
                }
            } else {
                if let Some(r) = w.rtf {
                    ok |= pb.setData_forType(Some(&NSData::with_bytes(r)), NSPasteboardTypeRTF);
                }
                if let Some(h) = w.html {
                    ok |= pb.setData_forType(Some(&NSData::with_bytes(h)), NSPasteboardTypeHTML);
                }
                if let Some(t) = w.text {
                    ok |= pb.setString_forType(&NSString::from_str(t), NSPasteboardTypeString);
                }
            }
        }
        ok.then(|| pb.changeCount())
    }
}

#[cfg(not(target_os = "macos"))]
mod imp {
    use super::{Clip, Write};

    pub fn change_count() -> isize {
        0
    }
    pub fn front_app() -> Option<(String, String, i32)> {
        None
    }
    pub fn read(_max: usize, _img: bool) -> Clip {
        Clip::default()
    }
    pub fn read_concealed(_max: usize, _img: bool) -> Clip {
        Clip::default()
    }
    pub fn write(_w: &Write) -> Option<isize> {
        None
    }
}

pub use imp::*;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn file_urls() {
        assert_eq!(file_url_path("file:///Users/r/Q4%20report.pdf"), Some(PathBuf::from("/Users/r/Q4 report.pdf")));
        assert_eq!(file_url_path("file://localhost/tmp/a/"), Some(PathBuf::from("/tmp/a")));
        assert_eq!(file_url_path("file:///%D0%BF.txt"), Some(PathBuf::from("/п.txt")));
        assert_eq!(file_url_path("https://x"), None);
    }
}
